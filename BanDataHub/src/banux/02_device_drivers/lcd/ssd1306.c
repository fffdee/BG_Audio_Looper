static void I2C_Delay(void)
{
    volatile uint32_t i;
    for (i = 0; i < 20; i++);
}

static void I2C_Start(void)
{
    SDA_HIGH();
    SCL_HIGH();
    I2C_Delay();
    SDA_LOW();
    I2C_Delay();
    SCL_LOW();
}

static void I2C_Stop(void)
{
    SDA_LOW();
    SCL_HIGH();
    I2C_Delay();
    SDA_HIGH();
    I2C_Delay();
}

static uint8_t I2C_WaitAck(void)
{
    uint8_t ack;
    SDA_HIGH();
    I2C_Delay();
    SCL_HIGH();
    I2C_Delay();
    ack = SDA_READ();
    SCL_LOW();
    I2C_Delay();
    return ack;
}

static void I2C_SendByte(uint8_t byte)
{
    uint8_t i;
    for (i = 0; i < 8; i++) {
        if (byte & 0x80) {
            SDA_HIGH();
        } else {
            SDA_LOW();
        }
        I2C_Delay();
        SCL_HIGH();
        I2C_Delay();
        SCL_LOW();
        I2C_Delay();
        byte <<= 1;
    }
}

static void SSD1306_WriteCommand(uint8_t cmd)
{
    I2C_Start();
    I2C_SendByte(HW_SSD1306_I2C_ADDR << 1);
    I2C_WaitAck();
    I2C_SendByte(0x00);
    I2C_WaitAck();
    I2C_SendByte(cmd);
    I2C_WaitAck();
    I2C_Stop();
}

static void SSD1306_WriteData(uint8_t data)
{
    I2C_Start();
    I2C_SendByte(HW_SSD1306_I2C_ADDR << 1);
    I2C_WaitAck();
    I2C_SendByte(0x40);
    I2C_WaitAck();
    I2C_SendByte(data);
    I2C_WaitAck();
    I2C_Stop();
}

static void I2C_GPIO_Init(void)
{
    GPIO_RegOneBitSet(GPIO_A_OE, (1 << HW_SSD1306_SCL_PIN));
    GPIO_RegOneBitClear(GPIO_A_IE, (1 << HW_SSD1306_SCL_PIN));
    GPIO_RegOneBitSet(GPIO_A_OE, (1 << HW_SSD1306_SDA_PIN));
    GPIO_RegOneBitClear(GPIO_A_IE, (1 << HW_SSD1306_SDA_PIN));
    SCL_HIGH();
    SDA_HIGH();
}

void SSD1306_Init(void)
{
    I2C_GPIO_Init();
    DelayMs(100);

    SSD1306_WriteCommand(0xAE);
    SSD1306_WriteCommand(0xD5);
    SSD1306_WriteCommand(0x80);
    SSD1306_WriteCommand(0xA8);
    SSD1306_WriteCommand(0x3F);
    SSD1306_WriteCommand(0xD3);
    SSD1306_WriteCommand(0x00);
    SSD1306_WriteCommand(0x40);
    SSD1306_WriteCommand(0x8D);
    SSD1306_WriteCommand(0x14);
    SSD1306_WriteCommand(0x20);
    SSD1306_WriteCommand(0x00);
    SSD1306_WriteCommand(0xA1);
    SSD1306_WriteCommand(0xC8);
    SSD1306_WriteCommand(0xDA);
    SSD1306_WriteCommand(0x12);
    SSD1306_WriteCommand(0x81);
    SSD1306_WriteCommand(0xCF);
    SSD1306_WriteCommand(0xD9);
    SSD1306_WriteCommand(0xF1);
    SSD1306_WriteCommand(0xDB);
    SSD1306_WriteCommand(0x40);
    SSD1306_WriteCommand(0xA4);
    SSD1306_WriteCommand(0xA6);
    SSD1306_WriteCommand(0xAF);

    memset(g_ssd1306.buffer, 0, sizeof(g_ssd1306.buffer));
    g_ssd1306.initialized = 1;
    DBG("SSD1306 initialized OK\n");
}

void SSD1306_DeInit(void)
{
    SSD1306_DisplayOff();
    g_ssd1306.initialized = 0;
}

void SSD1306_Clear(void)
{
    memset(g_ssd1306.buffer, 0, sizeof(g_ssd1306.buffer));
}

void SSD1306_Update(void)
{
    uint8_t i;
    if (!g_ssd1306.initialized) return;

    for (i = 0; i < SSD1306_PAGES; i++) {
        SSD1306_WriteCommand(0xB0 + i);
        SSD1306_WriteCommand(0x00);
        SSD1306_WriteCommand(0x10);

        I2C_Start();
        I2C_SendByte(HW_SSD1306_I2C_ADDR << 1);
        I2C_WaitAck();
        I2C_SendByte(0x40);
        I2C_WaitAck();

        {
            uint8_t j;
            for (j = 0; j < SSD1306_WIDTH; j++) {
                I2C_SendByte(g_ssd1306.buffer[i * SSD1306_WIDTH + j]);
                I2C_WaitAck();
            }
        }
        I2C_Stop();
    }
}

void SSD1306_DrawPixel(uint8_t x, uint8_t y, uint8_t color)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;
    if (color) {
        g_ssd1306.buffer[x + (y / 8) * SSD1306_WIDTH] |= (1 << (y % 8));
    } else {
        g_ssd1306.buffer[x + (y / 8) * SSD1306_WIDTH] &= ~(1 << (y % 8));
    }
}

void SSD1306_DrawChar(uint8_t x, uint8_t y, char ch, uint8_t size, uint8_t color)
{
    uint8_t i, j;
    uint8_t idx;

    if (ch < 32 || ch > 126) ch = 32;
    idx = ch - 32;

    if (size == 1) {
        for (i = 0; i < 6; i++) {
            uint8_t line = font_6x8[idx][i];
            for (j = 0; j < 8; j++) {
                if (line & (1 << j)) {
                    SSD1306_DrawPixel(x + i, y + j, color);
                } else {
                    SSD1306_DrawPixel(x + i, y + j, !color);
                }
            }
        }
    } else {
        for (i = 0; i < 6; i++) {
            uint8_t line = font_6x8[idx][i];
            for (j = 0; j < 8; j++) {
                uint8_t dx, dy;
                for (dx = 0; dx < size; dx++) {
                    for (dy = 0; dy < size; dy++) {
                        if (line & (1 << j)) {
                            SSD1306_DrawPixel(x + i * size + dx, y + j * size + dy, color);
                        } else {
                            SSD1306_DrawPixel(x + i * size + dx, y + j * size + dy, !color);
                        }
                    }
                }
            }
        }
    }
}

void SSD1306_DrawString(uint8_t x, uint8_t y, const char *str, uint8_t size, uint8_t color)
{
    uint8_t x_offset = x;
    while (*str) {
        SSD1306_DrawChar(x_offset, y, *str, size, color);
        x_offset += (6 * size);
        if (x_offset > SSD1306_WIDTH - 6 * size) break;
        str++;
    }
}

void SSD1306_DrawLine(uint8_t x0, uint8_t y0, uint8_t x1, uint8_t y1, uint8_t color)
{
    int16_t dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int16_t dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int16_t sx = (x0 < x1) ? 1 : -1;
    int16_t sy = (y0 < y1) ? 1 : -1;
    int16_t err = dx - dy;

    while (1) {
        SSD1306_DrawPixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        {
            int16_t e2 = 2 * err;
            if (e2 > -dy) { err -= dy; x0 += sx; }
            if (e2 < dx) { err += dx; y0 += sy; }
        }
    }
}

void SSD1306_DrawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t color)
{
    SSD1306_DrawLine(x, y, x + w - 1, y, color);
    SSD1306_DrawLine(x, y + h - 1, x + w - 1, y + h - 1, color);
    SSD1306_DrawLine(x, y, x, y + h - 1, color);
    SSD1306_DrawLine(x + w - 1, y, x + w - 1, y + h - 1, color);
}

void SSD1306_FillRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t color)
{
    uint8_t i, j;
    for (i = x; i < x + w; i++) {
        for (j = y; j < y + h; j++) {
            SSD1306_DrawPixel(i, j, color);
        }
    }
}

void SSD1306_SetContrast(uint8_t contrast)
{
    SSD1306_WriteCommand(0x81);
    SSD1306_WriteCommand(contrast);
}

void SSD1306_DisplayOn(void)
{
    SSD1306_WriteCommand(0x8D);
    SSD1306_WriteCommand(0x14);
    SSD1306_WriteCommand(0xAF);
}

void SSD1306_DisplayOff(void)
{
    SSD1306_WriteCommand(0x8D);
    SSD1306_WriteCommand(0x10);
    SSD1306_WriteCommand(0xAE);
}

void SSD1306_InvertDisplay(uint8_t invert)
{
    if (invert) {
        SSD1306_WriteCommand(0xA7);
    } else {
        SSD1306_WriteCommand(0xA6);
    }
}

